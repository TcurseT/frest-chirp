/**
 * Build the full mock result object for any classifier class.
 */
export function buildMockResult(name) {
  const meta = getBirdMeta(name)
  const sci  = toScientificStub(name)

  // Simulate a realistic confidence score (70–96 %)
  const confidence = parseFloat((70 + Math.random() * 26).toFixed(1))

  return {
    name,
    scientificName: sci ?? `${name.split(' ').slice(-1)[0]} sp.`,
    confidence,
    habitat: meta.habitat,
    region:  meta.region,
    description: meta.description,
  }
}

/** Pick a random species from the classifier and build its result object */
export function randomClassifierResult() {
  const name = CLASSIFIER_CLASSES[Math.floor(Math.random() * CLASSIFIER_CLASSES.length)]
  return buildMockResult(name)
}
